let currentLang = 'ko';
try {
    const fromUrl = new URLSearchParams(location.search).get('lang');
    const saved = localStorage.getItem(LANG_KEY);
    if (I18N[fromUrl]) {
        currentLang = fromUrl; localStorage.setItem(LANG_KEY, fromUrl);
        // 주소의 ?lang= 은 한 번만 쓰고 지운다. 남겨 두면 새로고침할 때마다 설정에서 바꾼 언어가 되돌아간다.
        history.replaceState(history.state, '', location.pathname + location.hash);
    }
    else if (I18N[saved]) currentLang = saved;
    else currentLang = (navigator.language || 'ko').toLowerCase().startsWith('ko') ? 'ko' : 'en';
} catch (error) {
    currentLang = (navigator.language || 'ko').toLowerCase().startsWith('ko') ? 'ko' : 'en';
}

function t(key, vars) {
    let text = I18N[currentLang][key] ?? I18N.ko[key] ?? key;
    if (vars) for (const [name, value] of Object.entries(vars)) text = text.replace('{' + name + '}', value);
    return text;
}

// data-i18n 속성이 붙은 정적 문구를 현재 언어로 교체
function applyStaticI18n() {
    document.documentElement.lang = currentLang;
    document.title = t('appName');
    document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
    document.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = t(el.dataset.i18nPh); });
    document.querySelectorAll('[data-i18n-aria]').forEach(el => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
    document.querySelectorAll('[data-href-ko]').forEach(el => { el.href = currentLang === 'ko' ? el.dataset.hrefKo : el.dataset.hrefEn; });
    const description = document.querySelector('meta[name="description"]');
    if (description) description.content = t('metaDescription');
    const appleTitle = document.querySelector('meta[name="apple-mobile-web-app-title"]');
    if (appleTitle) appleTitle.content = t('appName');
    const manifest = document.getElementById('manifestLink');
    if (manifest) manifest.href = currentLang === 'ko' ? 'manifest.webmanifest' : 'manifest.en.webmanifest';
}
